/// A simple logging adapter for the download groups package.
///
/// This class provides a unified logging interface that can be adapted
/// to any logging framework or custom logging solution. It's designed to
/// be lightweight and flexible, allowing you to integrate with your
/// existing logging infrastructure.
///
/// Example usage with debugPrint:
/// ```dart
/// final logger = AssetDownloaderLogger(debugPrint);
/// ```
///
/// Example usage with custom logging:
/// ```dart
/// final logger = AssetDownloaderLogger((message) {
///   MyCustomLogger.log('DownloadGroups: $message');
/// });
/// ```
///
/// Example usage with no-op logger:
/// ```dart
/// final logger = AssetDownloaderLogger((message) {}); // Silent logging
/// ```
class AssetDownloaderLogger {
  /// Creates a new logger with the specified logging function.
  ///
  /// [loggingTool] - A function that handles log messages.
  ///   Should accept a single String parameter and return void.
  AssetDownloaderLogger(this.loggingTool);

  /// The underlying logging function that processes messages.
  ///
  /// This function is called for all log messages generated by the
  /// download groups package. It can be any function that accepts
  /// a string, such as debugPrint, a custom logger, or a no-op function.
  final void Function(String) loggingTool;

  /// Logs an exception with its stack trace.
  ///
  /// This method formats the exception and stack trace into a readable
  /// string and passes it to the underlying logging function.
  ///
  /// [e] - The exception object to log
  /// [t] - The stack trace associated with the exception
  ///
  /// Example output:
  /// ```
  /// Exception: SocketException: Connection refused
  /// #0      _MyClass._downloadFile (package:my_app/src/download.dart:45:12)
  /// #1      _MyClass.downloadAssets (package:my_app/src/download.dart:23:17)
  /// ```
  Future<void> exception(Object e, StackTrace t) async {
    loggingTool('Exception: $e\n$t');
  }

  /// Logs a general message.
  ///
  /// This method passes the message directly to the underlying logging function
  /// without any additional formatting.
  ///
  /// [message] - The message to log
  ///
  /// Example:
  /// ```dart
  /// await logger.message('Starting download of 12 assets...');
  /// await logger.message('Download completed successfully');
  /// ```
  Future<void> message(String message) async {
    loggingTool(message);
  }
}
